create or replace view public.link_rrss_public_posts_v as
select
  p.id,pr.business_id,a.source_id,p.account_id,a.platform,a.username,
  p.external_post_id,p.platform_post_id,p.status,p.media_type,p.content,
  p.thumbnail_url,p.post_url,p.published_at,p.scheduled_for,p.metrics,
  p.first_seen_at,p.last_seen_at,p.updated_at
from public.link_rrss_posts p
join public.link_rrss_accounts a on a.id=p.account_id
join public.link_rrss_sources s on s.id=a.source_id
join public.link_rrss_profiles pr on pr.id=s.profile_id;

create or replace view public.link_rrss_public_memory_v as
select
  m.account_id,pr.business_id,a.source_id,a.platform,a.username,
  m.post_count,m.earliest_post_at,m.latest_post_at,m.last_successful_sync_at,
  m.history_backfilled_at,m.history_status,m.updated_at
from public.link_rrss_account_memory m
join public.link_rrss_accounts a on a.id=m.account_id
join public.link_rrss_sources s on s.id=a.source_id
join public.link_rrss_profiles pr on pr.id=s.profile_id;

grant select on public.link_rrss_public_posts_v to anon, authenticated;
grant select on public.link_rrss_public_memory_v to anon, authenticated;
